"""Build G* for a language from inputs/<lang>/ and write outputs/<lang>/.

Usage: python scripts/build_gstar.py [lang]     (default: tinyq)
"""
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from gtrans.model import load_grammar, load_grammar_explicit, load_table   # noqa: E402
from gtrans.kinds import all_kinds                          # noqa: E402
from gtrans.core import build                               # noqa: E402
from gtrans.labels import LABELS                            # noqa: E402
from gtrans.writer import write_text, write_json, summary   # noqa: E402


def main(lang="tinyq"):
    inp, out = ROOT / "inputs" / lang, ROOT / "outputs" / lang
    out.mkdir(parents=True, exist_ok=True)
    if (inp / "schema.json").exists():             # TinyQ: grammar template + schema
        g = load_grammar(inp / "grammar.json", inp / "schema.json")
    else:                                          # MySQL: explicit grammar written by make_inputs.py
        g = load_grammar_explicit(inp / "grammar.json")
    T = load_table(inp / "table_T.json")
    kinds = all_kinds(g, T)
    raw, rules, starts = build(g, T)
    write_text(out / "Gstar.txt", rules, raw, g, f"G* for {lang} (generated by GTrans from G and T)")
    write_json(out / "Gstar.json", rules, g)
    table, _ = summary(rules, raw, g, kinds)
    all_heads = {(s, l) for s in g.sorts for l in LABELS}
    kept = {r.head for r in rules}
    dropped = sorted(all_heads - kept)
    gl = ["# Grammar G (built from grammar.json and schema.json)", ""]
    for s in g.sorts:
        alts = [p.name for p in g.by_sort(s)]
        gl.append(f"- {s} → " + " | ".join(alts))
    lines = [f"# G* for {lang}: summary", "",
             f"Inputs: {inp.relative_to(ROOT)}/grammar.json" + (", schema.json" if (inp / "schema.json").exists() else "") + ", table_T.json", "",
             f"G has {len(g.productions)} productions over {len(g.sorts)} non-terminals; "
             f"G* has {len(kept)} labelled non-terminals and {len(rules)} rules.", "",
             table, "",
             "Rules per labelled non-terminal (after reduction):", ""]
    c = Counter(r.head for r in rules)
    for h in sorted(c, key=lambda h: (h[0], h[1])):
        lines.append(f"- {h[0]}[{h[1]}]: {c[h]}")
    lines += ["", "Labelled non-terminals removed by the reduction (they derive no pair, or are unreachable):", ""]
    lines += [f"- {s}[{l}]" for s, l in dropped]
    lines += ["", *gl, ""]
    (out / "Gstar_summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:16]))


if __name__ == "__main__":
    main(*sys.argv[1:])
